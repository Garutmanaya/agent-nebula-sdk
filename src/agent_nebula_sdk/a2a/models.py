"""Typed A2A security metadata and authenticated request models.

Purpose
-------
Represent the security-related subset of an A2A Agent Card and the artifacts
needed to invoke an HTTP-based A2A server through the Phase 1 OAuth/DPoP
profile. Business messages, tasks, and skills remain owned by an A2A protocol
implementation or the consuming application.
"""

from __future__ import annotations

from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator


class A2AClientCredentialsFlow(BaseModel):
    """Describe the OAuth client-credentials flow in an A2A security scheme."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    token_url: str = Field(alias="tokenUrl")
    scopes: dict[str, str] = Field(default_factory=dict)


class A2AOAuthFlows(BaseModel):
    """Contain OAuth flows supported by the A2A server."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    client_credentials: A2AClientCredentialsFlow | None = Field(
        default=None,
        alias="clientCredentials",
    )


class A2AOAuth2SecurityScheme(BaseModel):
    """Represent the A2A OAuth2 security-scheme variant."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    type: Literal["oauth2"] = "oauth2"
    description: str | None = None
    flows: A2AOAuthFlows
    oauth2_metadata_url: str | None = Field(default=None, alias="oauth2MetadataUrl")


class A2ASecurityScheme(BaseModel):
    """Wrap one A2A security-scheme choice using the current object shape."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    oauth2_security_scheme: A2AOAuth2SecurityScheme | None = Field(
        default=None,
        alias="oauth2SecurityScheme",
    )

    @model_validator(mode="after")
    def require_one_scheme(self) -> A2ASecurityScheme:
        """Reject empty scheme wrappers that cannot authenticate a request."""
        if self.oauth2_security_scheme is None:
            raise ValueError("an OAuth2 security scheme is required")
        return self


class A2ASecurityRequirement(BaseModel):
    """Represent one A2A security requirement and its optional OAuth scopes."""

    model_config = ConfigDict(extra="allow", frozen=True)


class A2ASecurityProfile(BaseModel):
    """Carry the Agent Card security fragment generated by the SDK."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    security_schemes: dict[str, A2ASecurityScheme] = Field(alias="securitySchemes")
    security: tuple[dict[str, tuple[str, ...]], ...]
    resource: str


class A2AHttpRequest(BaseModel):
    """Describe one authenticated A2A HTTP request before transport execution."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    endpoint: str
    body: bytes
    headers: dict[str, str]


class A2AHttpResponse(BaseModel):
    """Expose one transport-neutral A2A HTTP response."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    status_code: int
    headers: dict[str, str]
    payload: dict[str, Any] | list[Any] | None
    raw_body: bytes
